def _pose(t: np.ndarray) -> Dict[str, List[float]]:
    return {'xyz': [float(v) for v in t[:3, 3]], 'quat_xyzw': [float(v) for v in frames.matrix_to_quat(t[:3, :3])]}


def extent_behind_body(body: np.ndarray, mount: np.ndarray, exit_tool0: np.ndarray,
                       axis_tool0: np.ndarray) -> Dict[str, Any]:
    """Where the body lies along the beam: s = distance behind the beam exit (0 at the exit, positive rearwards).

    The part of the body behind the rear side of the mount (s > mount s max) is reported with its box in tool0:
    a cable stub or handle there is collision geometry and is kept (never cut silently)."""
    s_body = (exit_tool0 - body) @ axis_tool0
    s_mount = (exit_tool0 - mount) @ axis_tool0
    rear = body[s_body > s_mount.max()]
    out: Dict[str, Any] = {
        'body_length_along_beam_mm': float(s_body.max() - s_body.min()),
        'body_s_range_mm': [float(s_body.min()), float(s_body.max())],
        'mount_s_range_mm': [float(s_mount.min()), float(s_mount.max())],
        'behind_mount_mm': float(max(0.0, s_body.max() - s_mount.max())),
        'note': 's = distance behind the beam exit along the beam axis; behind_mount = body beyond the rear side '
                'of the mount (kept in the mesh)',
    }
    if len(rear):
        out['behind_mount_box_tool0_mm'] = {'min': [float(v) for v in rear.min(axis=0)],
                                            'max': [float(v) for v in rear.max(axis=0)]}
    return out


def _assumptions(cmap: Dict[str, Any], tool0_method: str, tcp_method: str, tcp_behind: bool,
                 cable_method: Optional[str] = None) -> List[str]:
    t0, tcp = cmap['frames']['tool0'], cmap['frames']['tcp']
    out = []
    if tool0_method == 'map':
        out.append('Assumption: tool0 from the map (frames.tool0 origin_file_mm / z_file / x_file)')
    else:
        out.append('Assumption: tool0 estimated from the geometry (no REF_TOOL0 marker, OI-23): origin = flange axis '
                   'on the flange / mount contact plane, Z out of the robot')
        out.append(f"Assumption: tool0 yaw from the flange dowel-pin hole (radius {t0['pin_radius_mm']} mm) on tool0 "
                   f"{t0['pin_axis']} (ur_description wrist3 mesh); the head yaw on the flange is taken as modelled")
    if tcp_method == 'teach_ui':
        out.append('tcp_laser taught on the UI (CP-61): centre of the picked nozzle-mouth circle + stick-out along its '
                   'axis, beam out of the nozzle; DES-001 §5.3 TCP at the nozzle tip (Assumption until IPG data, OI-2)')
        out.append(f"beam_exit_tool0_mm = tcp - nozzle_len_mm ({tcp['nozzle_len_mm']} mm) * beam_axis: the parametric "
                   'collision nozzle (CP-56) covers the last nozzle_len_mm before the TCP')
    elif tcp_method == 'map':
        out.append('Assumption: tcp_laser from the map: frames.tcp point_file_mm = nozzle tip + stick-out (TCP), '
                   'axis_file = beam out of the nozzle (no REF_TCP marker, OI-23; UI teach later, CP-61)')
        out.append(f"beam_exit_tool0_mm = tcp - nozzle_len_mm ({tcp['nozzle_len_mm']} mm) * beam_axis: the parametric "
                   'collision nozzle (CP-56) covers the last nozzle_len_mm before the TCP')
        if tcp_behind:
            out.append('Warning: the map TCP lies behind the flange plane (tool0 z < 0); accepted because it was set '
                       'explicitly')
    else:
        out.append('Assumption: beam axis = axis line of the revolved faces of the head body that reach farthest from '
                   'tool0; beam exit = farthest point of the body on that line (no REF_TCP marker, OI-23)')
        out.append(f"Assumption: tcp_laser = beam exit + parametric nozzle {tcp['nozzle_len_mm']} mm along the beam "
                   '(CP-56: nozzle is cell data; I2 / OI-15)')
    if cable_method == 'rear_estimate':
        out.append('Assumption: conduit exit = farthest revolved end of the head behind the flange (rear automatic '
                   'beam estimate, refused as a TCP), axis outward along it; set frames.cable_exit to replace it')
    elif cable_method == 'map':
        out.append('Assumption: conduit exit from the map (frames.cable_exit point_file_mm / axis_file)')
    out.append('Assumption: tcp_laser X = tool0 X made orthogonal to the beam (tool yaw is swept, ψ)')
    out.append('The head body is a surface model: its mesh is an open triangle set (collision on triangles, no '
               'inside test)')
    return out


def _recover(root: Path) -> None:
    """Leftovers of a crashed export-head (call under the export lock)."""
    for path in root.glob(f'{STAGING_PREFIX}*'):
        shutil.rmtree(path, ignore_errors=True)
    model = root / 'cell' / 'model'
    if model.is_dir():
        for path in model.glob(f'.{HEAD_DIR}.trash-*'):
            shutil.rmtree(path, ignore_errors=True)
        for path in model.glob(f'.{HEAD_DIR}.old-*'):
            if (model / HEAD_DIR).exists():
                shutil.rmtree(path, ignore_errors=True)
            else:
                os.replace(path, model / HEAD_DIR)


STAGING_PREFIX = '.staging-export-head-'


def export_head(step: Path, map_path: Path, repo_root: Path, created_by: str,
                teach: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Write ``<repo>/cell/model/head/`` (see module docstring) under the repository export lock; return a summary.

    ``teach`` (CP-61): ``{component, edge_id, reverse, stickout_mm, taught_by}`` — the TCP comes from that nozzle-mouth
    circle instead of the map / the beam estimate."""
    root = Path(repo_root)
    root.mkdir(parents=True, exist_ok=True)
    with scene.export_lock(root):
        _recover(root)
        return _export_head(Path(step), Path(map_path), root, created_by, teach)


BEAM_TOL = 1e-6  # numerical tolerance of the beam-direction checks (unit vector component / mm)


def check_teach_component(tree: List[Dict[str, Any]], links: Dict[str, List[int]], component: str) -> str:
    """Return the head link that owns the teach component; refuse a component outside the head's ``head_links``
    (review I2: e.g. a circle on the robot flange or on another cell component)."""
    owned = {j: link for link, idx in links.items() for i in idx for j in _subtree(tree, i)}
    hits = [i for i in owned if tree[i]['instance_name'] == component]
    if len(hits) != 1:
        raise HeadError(f'TCP teach: component {component!r} is not in head_links (or not unique there: '
                        f'{len(hits)} matches); pick the nozzle-mouth circle on a component of the head links '
                        f'{sorted(links)}')
    return owned[hits[0]]


def check_beam_direction(point_t0: np.ndarray, axis_t0: np.ndarray, source: str) -> None:
    """Refuse a TCP whose beam points back towards tool0 (review I2).

    DES-001 §5.3: tcp_laser Z = beam direction, out of the nozzle. A beam with ``dot(axis, tcp) <= 0`` in tool0 runs
    back towards the flange: the parametric nozzle would sit beyond the tip and the planner would put the head on
    the wrong side of the seam. The real LightWELD head (beam (0.866, 0, 0.5), TCP (43.8, 0, 279.6) mm) passes."""
    if float(axis_t0 @ point_t0) <= BEAM_TOL:
        raise HeadError(f'{source}: the beam axis {np.round(axis_t0, 5).tolist()} points back towards tool0 (TCP '
                        f'{np.round(point_t0, 3).tolist()} mm in tool0, dot = {float(axis_t0 @ point_t0):.3f} mm): '
                        'tcp_laser Z must be the beam out of the nozzle, away from the flange (DES-001 §5.3). Flip '
                        'frames.tcp axis_file / do not reverse the taught circle')


def taught_tcp(step: Path, teach: Dict[str, Any], body_shape) -> Dict[str, Any]:
    """CP-61: TCP from the nozzle-mouth circle picked on the UI (file frame, mm).

    ``teach``: ``{component, edge_id, reverse, stickout_mm}``. Beam axis = circle axis pointing away from the centre of
    the beam link's bounding box (out of the nozzle), flipped by ``reverse``; TCP = circle centre + stick-out along it.
    """
    from awm_geometry import circle_pick, part, topology

    loaded = part.load_part(step, teach['component'])
    try:
        circle = circle_pick.circle_frame(circle_pick.edge_by_id(loaded.shape, teach['edge_id']))
    except GeometryError as exc:
        raise HeadError(f'TCP teach {teach["component"]} {teach["edge_id"]}: {exc}') from exc
    centre, axis = np.array(circle['center_mm']), np.array(circle['axis'])
    lo, hi = topology.bbox(body_shape)
    if axis @ (centre - (np.asarray(lo) + np.asarray(hi)) / 2.0) < 0.0:
        axis = -axis
    if teach.get('reverse'):
        axis = -axis
    stickout = float(teach.get('stickout_mm') or 0.0)
    return {'point_file_mm': [float(v) for v in centre + stickout * axis], 'axis_file': [float(v) for v in axis],
            'radius_mm': circle['radius_mm']}


def _cable_exit(entry: Optional[Dict[str, Any]], tool0_T_file: np.ndarray, geometry_tcp,
                nozzle: float) -> Optional[Tuple[np.ndarray, np.ndarray, Dict[str, Any]]]:
    """Fiber / wire conduit exit of the head for the xacro conduit capsule: ``(point_t0, axis_t0, estimate)`` or None.

    1. map ``frames.cable_exit`` (point_file_mm + axis_file, file frame; axis outward along the cable);
    2. else the rear automatic beam estimate that is refused as a TCP (behind the flange plane): the farthest revolved
       end of the head is the cable / connector end, so exit = its beam exit (= its tcp - nozzle_len_mm * axis) and
       axis = its direction (outward, away from the head);
    3. else None (no invented default)."""
    if entry is not None:
        point = (tool0_T_file @ np.append(np.asarray(entry['point_file_mm'], dtype=float), 1.0))[:3]
        axis = tool0_T_file[:3, :3] @ np.asarray(entry['axis_file'], dtype=float)
        return point, axis, {'method': 'map'}
    if isinstance(geometry_tcp, tuple) and (geometry_tcp[0] + nozzle * geometry_tcp[1])[2] < 0.0:
        exit_t0, axis_t0, beam = geometry_tcp  # its tcp is behind the flange (geometry_estimate behind_flange)
        return exit_t0, axis_t0, {'method': 'rear_estimate', 'residuals': beam['residuals']}
    return None


def _export_head(step: Path, map_path: Path, root: Path, created_by: str,
                 teach: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    if not step.is_file():
        raise HeadError(f'STEP file not found: {step}')
    cmap = load_head_map(map_path, step)
    LOG.info('A18 reading head assembly %s', step)
    tree, _unit_src = assembly.component_tree(step, cylinders=False, shapes=True)
    _head, links = resolve_links(tree, cmap)
    shapes = {link: assembly.compound([tree[i]['_shape'] for i in idx]) for link, idx in links.items()}
    t0, tcp_map = cmap['frames']['tool0'], cmap['frames']['tcp']

    estimates: Dict[str, Any] = {}
    geometry_tool0 = None
    if {'robot_link', 'mount'} <= set(t0):
        try:
            robot = _component(tree, t0['robot_link'], 'frames.tool0.robot_link')['_shape']
            mount = _component(tree, t0['mount'], 'frames.tool0.mount')['_shape']
            geometry_tool0 = estimate_tool0(robot, mount, float(t0['pin_radius_mm']), t0['pin_axis'])
        except HeadError as exc:
            if 'origin_file_mm' not in t0:
                raise
            geometry_tool0 = exc
    if 'origin_file_mm' in t0:
        file_T_tool0 = tool0_from_map(t0)
        est: Dict[str, Any] = {'method': 'map'}
        if isinstance(geometry_tool0, tuple):
            delta = frames.invert(file_T_tool0) @ geometry_tool0[0]
            est['geometry_estimate'] = {'offset_mm': float(np.linalg.norm(delta[:3, 3])),
                                        'angle_deg': float(units.rad_to_deg(
                                            frames.rotation_angle_between(np.eye(3), delta[:3, :3]))),
                                        'residuals': geometry_tool0[1]}
        elif geometry_tool0 is not None:
            est['geometry_estimate'] = {'error': str(geometry_tool0)}
    else:
        file_T_tool0, residuals = geometry_tool0
        est = {'method': 'flange_contact', 'robot_link': t0['robot_link'], 'mount': t0['mount'],
               'pin_axis': t0['pin_axis'], 'residuals': residuals}
    estimates['tool0'] = est

    beam_shape = shapes[tcp_map['beam_link']]
    nozzle = float(tcp_map['nozzle_len_mm'])
    taught = None
    if teach is not None:
        check_teach_component(tree, links, teach['component'])
        taught = taught_tcp(step, teach, beam_shape)
        tcp_map = dict(tcp_map, point_file_mm=taught['point_file_mm'], axis_file=taught['axis_file'])
    inv = frames.invert(file_T_tool0)
    geometry_tcp = None
    try:
        beam = estimate_beam(beam_shape, file_T_tool0)
        exit_t0 = (inv @ np.append(beam['exit_mm'], 1.0))[:3]
        axis_t0 = inv[:3, :3] @ beam['axis']
        geometry_tcp = (exit_t0, axis_t0, beam)
    except HeadError as exc:
        if 'point_file_mm' not in tcp_map:
            raise
        geometry_tcp = exc
    if 'point_file_mm' in tcp_map:
        # Explicit TCP (later taught on the UI, CP-61 draft): point = nozzle tip + stick-out, axis = beam out of the
        # nozzle. The beam exit is put nozzle_len_mm behind it, so the head.yaml / xacro rule
        # tcp = beam_exit + nozzle_len_mm * beam_axis holds and the parametric nozzle ends at the TCP (CP-56).
        point_t0 = (inv @ np.append(_vec3(tcp_map['point_file_mm'], 'frames.tcp.point_file_mm'), 1.0))[:3]
        axis_t0 = inv[:3, :3] @ _unit(tcp_map['axis_file'], 'frames.tcp.axis_file')
        tool0_T_tcp = tcp_pose(point_t0, axis_t0, 0.0)
        exit_t0 = point_t0 - nozzle * axis_t0
        behind = bool(point_t0[2] < 0.0)
        if behind and taught is not None:
            raise HeadError(f'taught TCP lies behind the flange plane (tool0 z {point_t0[2]:.3f} mm): the picked circle '
                            f'{teach["component"]} {teach["edge_id"]} is not the nozzle mouth (cable / connector end?)')
        if taught is not None:
            check_beam_direction(point_t0, axis_t0, f'taught TCP {teach["component"]} {teach["edge_id"]}'
                                 + (' (reversed)' if teach.get('reverse') else ''))
            if axis_t0[2] <= BEAM_TOL:
                raise HeadError(f'taught TCP {teach["component"]} {teach["edge_id"]}: the beam axis '
                                f'{np.round(axis_t0, 5).tolist()} points back towards tool0 (no component along '
                                'tool0 +Z): the beam must leave the nozzle away from the flange (DES-001 §5.3)')
        else:
            check_beam_direction(point_t0, axis_t0, 'frames.tcp from the map')
        if behind:
            LOG.warning('A18 frames.tcp from the map lies behind the flange plane (tool0 z %.3f mm): accepted as '
                        'set, recorded in head.yaml', point_t0[2])
        est = {'method': 'map', 'behind_flange': behind, 'tcp_z_tool0_mm': float(point_t0[2])}
        if taught is not None:
            est.update(method='teach_ui', component=teach['component'], edge_id=teach['edge_id'],
                       reversed=bool(teach.get('reverse')), stickout_mm=float(teach.get('stickout_mm') or 0.0),
                       mouth_radius_mm=float(taught['radius_mm']), taught_by=teach.get('taught_by') or 'unknown',
                       taught_at=jsonio.utc_now_iso())
        if isinstance(geometry_tcp, tuple):
            g_tcp = tcp_pose(geometry_tcp[0], geometry_tcp[1], nozzle)
            est['geometry_estimate'] = {
                'tcp_tool0_mm': [float(v) for v in g_tcp[:3, 3]],
                'beam_axis_tool0': [float(v) for v in geometry_tcp[1]],
                'tcp_offset_mm': float(np.linalg.norm(g_tcp[:3, 3] - tool0_T_tcp[:3, 3])),
                'axis_angle_deg': _angle_deg(g_tcp[:3, 2], axis_t0) if g_tcp[:3, 2] @ axis_t0 >= 0
                else 180.0 - _angle_deg(g_tcp[:3, 2], axis_t0),
                'behind_flange': bool(g_tcp[2, 3] < 0.0),
                'residuals': geometry_tcp[2]['residuals']}
        else:
            est['geometry_estimate'] = {'error': str(geometry_tcp)}
        beam_axis = axis_t0
    else:
        exit_t0, axis_t0, beam = geometry_tcp
        tool0_T_tcp = tcp_pose(exit_t0, axis_t0, nozzle)
        if tool0_T_tcp[2, 3] < 0.0:
            raise HeadError(
                f'automatic beam estimate puts tcp_laser behind the flange plane (tool0 z {tool0_T_tcp[2, 3]:.3f} mm, '
                f'beam exit {np.round(exit_t0, 3).tolist()} mm, axis {np.round(axis_t0, 5).tolist()} in tool0): the '
                'farthest revolved faces are a cable / connector end, not the nozzle. Set the nozzle tip explicitly '
                'in the map: frames.tcp point_file_mm (TCP, file mm) and axis_file (beam out of the nozzle, file '
                'frame); later taught on the UI (CP-61)')
        beam_axis = axis_t0
        est = {'method': 'beam_axis', 'beam_link': tcp_map['beam_link'], 'residuals': beam['residuals'],
               'behind_flange': False,
               'beam_to_tool0_z_deg': float(units.rad_to_deg(np.arccos(np.clip(axis_t0[2], -1.0, 1.0)))),
               'beam_exit_offset_from_tool0_z_mm': float(np.hypot(exit_t0[0], exit_t0[1]))}
        if beam['runner_up'] is not None:
            est['runner_up'] = beam['runner_up']
    estimates['tcp'] = est

    cable_exit = _cable_exit(cmap['frames'].get('cable_exit'), inv, geometry_tcp, nozzle)
    if cable_exit is not None:
        estimates['cable_exit'] = cable_exit[2]

    meshes = {link: link_meshes(shapes[link], file_T_tool0, link) for link in LINKS}
    extent = extent_behind_body(meshes[tcp_map['beam_link']]['verts'], meshes['head_mount']['verts'],
                                exit_t0, beam_axis)

    # --- all computed and checked: write into a staging folder, then move into place ---------------------------
    out_dir = root / 'cell' / 'model' / HEAD_DIR
    staging = root / f'{STAGING_PREFIX}{os.getpid()}'
    if staging.exists():
        shutil.rmtree(staging)
    stage = staging / HEAD_DIR
    stage.mkdir(parents=True)
    try:
        link_docs: Dict[str, Any] = {}
        for link, m in meshes.items():
            hull.write_stl(stage / f'{link}.stl', m['verts'], m['tris'])
            hull.write_stl(stage / f'{link}_hull.stl', m['hull_verts'], m['hull_tris'])
            link_docs[link] = {
                'components': [tree[i]['path'] for i in links[link]],
                'mesh': {'file': f'{link}.stl', 'sha256': sha256_file(stage / f'{link}.stl'),
                         'vertices': int(len(m['verts'])), 'triangles': int(len(m['tris'])), 'closed': m['closed']},
                'hull': {'file': f'{link}_hull.stl', 'sha256': sha256_file(stage / f'{link}_hull.stl'),
                         'vertices': int(len(m['hull_verts'])), 'triangles': int(len(m['hull_tris']))},
                'faces_in': m['faces_in'], 'faces_meshed': m['faces_meshed'],
                'brep_area_mm2': m['brep_area_mm2'], 'mesh_area_mm2': m['mesh_area_mm2'],
            }
            if m['retried']:
                link_docs[link]['retried_faces'] = m['retried']
        doc = dict(jsonio.make_header(created_by, [step, map_path], out_dir), schema_version=SCHEMA_VERSION)
        doc.update({
            'schema': SCHEMA, 'head_model': 'H-CAD', 'unit': 'mm', 'frame': 'tool0',
            'source': {'file': step.name, 'sha256': sha256_file(step), 'map': map_path.name,
                       'map_sha256': sha256_file(map_path), 'file_up_axis': cmap['source']['up_axis']},
            'tessellation': {'mesh': {'linear_deflection_mm': MESH_LINEAR_DEFLECTION_MM,
                                      'angular_deflection_deg': MESH_ANGULAR_DEFLECTION_DEG, 'weld_mm': MESH_WELD_MM},
                             'hull': {'linear_deflection_mm': HULL_LINEAR_DEFLECTION_MM,
                                      'angular_deflection_deg': HULL_ANGULAR_DEFLECTION_DEG,
                                      'note': 'hull of this tessellation plus every full-mesh vertex'}},
            'file_T_tool0_mm': _pose(file_T_tool0),
            'tool0_T_tcp_mm': _pose(tool0_T_tcp),
            'beam_axis_tool0': [float(v) for v in beam_axis],
            'beam_exit_tool0_mm': [float(v) for v in exit_t0],
            'nozzle_len_mm': nozzle,
            'tcp_rule': 'tcp = beam_exit + nozzle_len_mm * beam_axis (for another nozzle length use the same rule)',
            'cable_exit_tool0_mm': None if cable_exit is None else [float(v) for v in cable_exit[0]],
            'cable_axis_tool0': None if cable_exit is None else [float(v) for v in cable_exit[1]],
            'cable_exit_source': None if cable_exit is None else cable_exit[2]['method'],
            'links': link_docs,
            'estimates': estimates,
            'assumptions': _assumptions(cmap, estimates['tool0']['method'], estimates['tcp']['method'],
                                        estimates['tcp']['behind_flange'],
                                        None if cable_exit is None else cable_exit[2]['method']),
            'extent_behind_body_mm': extent,
        })
        miniyaml.dump(doc, stage / 'head.yaml',
                      header='H-CAD head model (generated by awm_geometry export-head; do not edit). Lengths mm, '
                             'quaternions xyzw, meshes in tool0.')
        scene.swap_dirs([(stage, out_dir)])
    finally:
        shutil.rmtree(staging, ignore_errors=True)

    return {'head_dir': str(out_dir), 'tool0_T_tcp_mm': doc['tool0_T_tcp_mm'],
            'beam_axis_tool0': doc['beam_axis_tool0'], 'beam_exit_tool0_mm': doc['beam_exit_tool0_mm'],
            'methods': {k: v['method'] for k, v in estimates.items()},
            'triangles': {link: {'mesh': d['mesh']['triangles'], 'hull': d['hull']['triangles']}
                          for link, d in link_docs.items()},
            'extent_behind_body_mm': extent}
