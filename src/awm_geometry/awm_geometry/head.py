"""LightWELD head model H-CAD from the Fusion head CAD (WP-S S.5c Task 1; A18, DES-001 §5.3 / §5.4, ADR-16, CP-56).

Input: a STEP assembly that holds the (posed) UR arm, the head mount and the LightWELD head, and a role map
``cad_map_head.yaml`` (data, never source: component names, links, frame rules). Output, all in mm, in the
``tool0`` frame, written to ``<repo>/cell/model/head/`` (D14 meshes generated by A18):

* ``head_body.stl``, ``head_mount.stl`` — the full tessellation of every B-Rep face of each link (chord
  ``MESH_LINEAR_DEFLECTION_MM``); the verdict collision geometry (Truong 2026-11-05: accuracy before schedule).
  The LightWELD head is a surface model (no solid): its mesh is an open triangle set, not a closed shell;
* ``head_body_hull.stl``, ``head_mount_hull.stl`` — convex hulls (comparison only), built from a finer tessellation
  (``HULL_LINEAR_DEFLECTION_MM``) plus every vertex of the full mesh, so a hull contains its full mesh;
* ``head.yaml`` — header (inputs SHA-256), ``file_T_tool0_mm``, ``tool0_T_tcp_mm``, ``beam_axis_tool0``,
  ``beam_exit_tool0_mm``, ``nozzle_len_mm``, per-link mesh records, ``estimates`` (method + residuals per frame),
  ``assumptions``, ``extent_behind_body_mm``.

Frames (every one an **Assumption** until ``REF_TOOL0`` / ``REF_TCP`` markers exist, OI-23; each can be replaced in
the map, then recorded as ``method: map`` with the geometric estimate kept for comparison):

* ``tool0``: the robot's last link (map ``frames.tool0.robot_link``) and the mount (``frames.tool0.mount``) touch on
  a plane (antiparallel planar faces, gap <= ``CONTACT_GAP_MM``). Z = outward normal of the robot face (out of the
  robot); origin = axis of the robot link's largest cylindrical face parallel to Z, intersected with the contact
  plane. Yaw: the flange's dowel-pin hole (cylinder of radius ``pin_radius_mm`` off the axis) lies on the tool0 axis
  named by ``pin_axis`` (ur_description wrist3 mesh: pin hole and tool connector on tool0 -Y).
* beam axis: the revolved faces (cylinders, cones) of the beam link grouped by common axis line; among the groups
  whose faces reach within ``REACH_BAND_MM`` of the farthest reach from tool0, the one with the largest face area is
  the beam line (the optics bore, not a screw hole beside it); its direction points to the far end. Beam exit =
  farthest point of the link on that line (line / B-Rep intersection, and the group's own face vertices). Reach =
  largest distance from tool0 of the group's B-Rep vertices and face centroids.
* ``tcp_laser`` = beam exit + ``nozzle_len_mm`` along the beam (parametric nozzle beyond the CAD, CP-56; 0 if the
  nozzle is part of the CAD); Z = beam direction, X = tool0 X made orthogonal (ψ sweep absorbs the yaw). An automatic
  estimate whose TCP lies behind the flange plane (tool0 z < 0) is refused: that is a cable / connector end, not the
  nozzle (bug of 2026-11-06); the map must then name the TCP.
* map override ``frames.tcp.point_file_mm`` / ``axis_file`` (file frame): the TCP itself (nozzle tip + stick-out) and
  the beam direction out of the nozzle (later taught on the UI, CP-61 draft). It is accepted wherever it lies
  (recorded, ``behind_flange``); head.yaml then holds ``beam_exit_tool0_mm = tcp - nozzle_len_mm * beam_axis`` so
  the rule ``tcp = beam_exit + nozzle_len_mm * beam_axis`` (xacro) holds and the parametric collision nozzle ends at
  the TCP. The automatic estimate is kept beside it for comparison.
* conduit exit (additive keys ``cable_exit_tool0_mm``, ``cable_axis_tool0`` = outward along the cable, and
  ``cable_exit_source`` = ``map`` / ``rear_estimate``; read by the cell-sim hcad xacro for the fiber / wire conduit
  capsule): map ``frames.cable_exit`` (point_file_mm + axis_file, file frame) or else the rear automatic estimate that
  is refused as a TCP (its beam exit and direction); null when neither exists (no default is invented).
"""

