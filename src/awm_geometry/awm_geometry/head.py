class HeadError(GeometryError):
    """The head map is invalid, does not fit the assembly, or a frame cannot be estimated."""


# --- map ------------------------------------------------------------------------------------------------------

def _vec3(value, what: str) -> np.ndarray:
    arr = np.asarray(value, dtype=float) if isinstance(value, (list, tuple)) else None
    if arr is None or arr.shape != (3,) or not np.isfinite(arr).all():
        raise HeadError(f'{what} must be 3 finite numbers, got {value!r}')
    return arr


def _unit(value, what: str) -> np.ndarray:
    v = _vec3(value, what)
    if abs(np.linalg.norm(v) - 1.0) > 1e-6:
        raise HeadError(f'{what} {v.tolist()} must have unit length')
    return v


def load_head_map(path: Path, step: Path) -> Dict[str, Any]:
    """Read and check the head map (schema ``cad_map/0.1`` with ``head_links`` and head frames).

    Not validated against ``v2/cad_map``: that schema requires the cell frames and has no head block yet
    (request to the contract owner); the checks below cover the head keys.
    """
    if not path.is_file():
        raise HeadError(f'head map not found: {path}')
    cmap = miniyaml.load(path)
    if not isinstance(cmap, dict) or cmap.get('schema') != MAP_SCHEMA:
        raise HeadError(f'{path}: schema must be {MAP_SCHEMA!r}')
    if cmap.get('match') != 'instance_name' or cmap.get('default') != 'deny':
        raise HeadError(f'{path}: only "match: instance_name" and "default: deny" are supported')
    source = cmap.get('source') or {}
    if source.get('unit') != 'mm':
        raise HeadError(f'{path}: source.unit must be mm')
    digest = sha256_file(step)
    if source.get('sha256') != digest:
        raise HeadError(f'{path}: source SHA-256 {source.get("sha256")} does not match {step.name} ({digest})')
    scene.world_R_file(source.get('up_axis'))
    roles = cmap.get('roles') or {}
    if set(roles) - set(ROLES):
        raise HeadError(f'{path}: roles {sorted(set(roles) - set(ROLES))} not allowed in a head map ({ROLES})')
    heads = roles.get('head_cad') or []
    if len(heads) != 1:
        raise HeadError(f'{path}: roles.head_cad must name exactly one component, found {len(heads)}')
    links = cmap.get('head_links') or {}
    if set(links) != set(LINKS) or not all(isinstance(v, list) and v for v in links.values()):
        raise HeadError(f'{path}: head_links must map each of {LINKS} to a non-empty list of instance names')
    fr = cmap.get('frames') or {}
    tool0, tcp = fr.get('tool0') or {}, fr.get('tcp') or {}
    override = {'origin_file_mm', 'z_file', 'x_file'} & set(tool0)
    if override and len(override) != 3:
        raise HeadError(f'{path}: frames.tool0 override needs origin_file_mm, z_file and x_file')
    estimate_keys = {'robot_link', 'mount', 'pin_radius_mm', 'pin_axis'}
    if not override and not estimate_keys <= set(tool0):
        raise HeadError(f'{path}: frames.tool0 needs {sorted(estimate_keys)} (or an override)')
    if 'pin_axis' in tool0 and tool0['pin_axis'] not in PIN_AXES:
        raise HeadError(f'{path}: frames.tool0.pin_axis must be one of {sorted(PIN_AXES)}')
    tcp_override = {'point_file_mm', 'axis_file'} & set(tcp)
    if tcp_override and len(tcp_override) != 2:
        raise HeadError(f'{path}: frames.tcp override needs point_file_mm and axis_file')
    cable = fr.get('cable_exit')
    if cable is not None:
        if not isinstance(cable, dict) or set(cable) != {'point_file_mm', 'axis_file'}:
            raise HeadError(f'{path}: frames.cable_exit needs exactly point_file_mm and axis_file')
        _vec3(cable['point_file_mm'], f'{path}: frames.cable_exit.point_file_mm')
        _unit(cable['axis_file'], f'{path}: frames.cable_exit.axis_file')
    if tcp.get('beam_link') not in LINKS:
        raise HeadError(f'{path}: frames.tcp.beam_link must be one of {LINKS}')
    nozzle = tcp.get('nozzle_len_mm')
    if not isinstance(nozzle, (int, float)) or isinstance(nozzle, bool) or nozzle < 0:
        raise HeadError(f'{path}: frames.tcp.nozzle_len_mm must be a number >= 0')
    return cmap


def _subtree(tree: List[Dict[str, Any]], root: int) -> List[int]:
    inside = {root}
    for node in tree:  # depth-first order: parents come first
        if node['parent'] in inside:
            inside.add(node['index'])
    return sorted(inside)


def resolve_links(tree: List[Dict[str, Any]], cmap: Dict[str, Any]) -> Tuple[int, Dict[str, List[int]]]:
    """Head component index and ``{link: [node indices]}``; default deny inside the head component too."""
    direct = scene.resolve_roles(tree, {'roles': cmap['roles']})
    head = [i for i, (role, _) in direct.items() if role == 'head_cad'][0]
    sub = _subtree(tree, head)
    links: Dict[str, List[int]] = {}
    owner: Dict[int, str] = {}
    problems = []
    for link in LINKS:
        links[link] = []
        for name in cmap['head_links'][link]:
            hits = [i for i in sub if i != head and tree[i]['instance_name'] == name]
            if len(hits) != 1:
                problems.append(f'{link}: {name!r} matches {len(hits)} components below the head component')
                continue
            for j in _subtree(tree, hits[0]):
                if j in owner:
                    problems.append(f'{tree[j]["path"]!r} is in {owner[j]} and {link}')
                owner[j] = link
            links[link].append(hits[0])
    loose = [tree[i]['path'] for i in sub if not tree[i]['is_assembly'] and tree[i]['bbox_mm'] is not None
             and i not in owner]
    if loose:
        problems.append('component(s) with geometry below the head in no link (default deny): ' + '; '.join(loose))
    if problems:
        raise HeadError('head map does not fit the assembly:\n  ' + '\n  '.join(problems))
    return head, links


def _component(tree: List[Dict[str, Any]], name: str, what: str) -> Dict[str, Any]:
    hits = [n for n in tree if n['parent'] is not None and n['instance_name'] == name]
    if len(hits) != 1:
        raise HeadError(f'{what} {name!r} matches {len(hits)} components (expected 1)')
    return hits[0]


# --- B-Rep face data ------------------------------------------------------------------------------------------

def _faces(shape: TopoDS_Shape) -> List:
    out, exp = [], TopExp_Explorer(shape, TopAbs_FACE)
    while exp.More():
        out.append(topods.Face(exp.Current()))
        exp.Next()
    return out


def _area_centroid(face) -> Tuple[float, np.ndarray]:
    props = GProp_GProps()
    brepgprop.SurfaceProperties(face, props)
    return float(props.Mass()), np.array(props.CentreOfMass().Coord())


def _planes(shape: TopoDS_Shape) -> List[Dict[str, Any]]:
    """Planar faces: outward normal (face orientation applied), offset ``d = n . x``, area, centroid."""
    out = []
    for face in _faces(shape):
        surf = BRepAdaptor_Surface(face)
        if surf.GetType() != GeomAbs_Plane:
            continue
        pln = surf.Plane()
        n = np.array(pln.Axis().Direction().Coord())
        if face.Orientation() == TopAbs_REVERSED:
            n = -n
        area, c = _area_centroid(face)
        out.append({'n': n, 'd': float(n @ np.array(pln.Location().Coord())), 'area': area, 'c': c})
    return out


def _revolved(shape: TopoDS_Shape, types=(GeomAbs_Cylinder,)) -> List[Dict[str, Any]]:
    """Cylindrical (and optionally conical) faces: axis direction, axis point, radius, area, centroid, face."""
    out = []
    for face in _faces(shape):
        surf = BRepAdaptor_Surface(face)
        kind = surf.GetType()
        if kind not in types:
            continue
        geo = surf.Cylinder() if kind == GeomAbs_Cylinder else surf.Cone()
        radius = geo.Radius() if kind == GeomAbs_Cylinder else geo.RefRadius()
        ax = geo.Axis()
        area, c = _area_centroid(face)
        out.append({'a': np.array(ax.Direction().Coord()), 'p': np.array(ax.Location().Coord()),
                    'r': float(radius), 'area': area, 'c': c, 'face': face})
    return out


def _angle_deg(a: np.ndarray, b: np.ndarray) -> float:
    """Angle between two lines (sign ignored), degrees."""
    return float(units.rad_to_deg(np.arccos(np.clip(abs(float(a @ b)), -1.0, 1.0))))


def _line_offset(p: np.ndarray, line_p: np.ndarray, line_a: np.ndarray) -> float:
    v = p - line_p
    return float(np.linalg.norm(v - (v @ line_a) * line_a))


# --- tool0 ----------------------------------------------------------------------------------------------------

def estimate_tool0(robot_link: TopoDS_Shape, mount: TopoDS_Shape, pin_radius_mm: float,
                   pin_axis: str) -> Tuple[np.ndarray, Dict[str, Any]]:
    """``file_T_tool0`` (4x4, mm) from the flange / mount contact and the dowel-pin hole; plus residuals."""
    cos_tol = np.cos(units.deg_to_rad(PARALLEL_DEG))
    robot_planes, mount_planes = _planes(robot_link), _planes(mount)
    pairs = [(r, m) for r in robot_planes for m in mount_planes
             if r['n'] @ m['n'] <= -cos_tol and abs(r['d'] + m['d']) <= CONTACT_GAP_MM]
    if not pairs:
        raise HeadError('no planar face of the mount lies on a planar face of the robot link (flange contact); '
                        'set frames.tool0 origin_file_mm / z_file / x_file in the map')
    best = max(pairs, key=lambda rm: min(rm[0]['area'], rm[1]['area']))
    z, d = best[0]['n'], best[0]['d']
    distinct = [r for r, _ in pairs if _angle_deg(r['n'], z) > PARALLEL_DEG or abs(r['d'] - d) > CONTACT_GAP_MM]
    if distinct:
        raise HeadError(f'mount and robot link touch on {1 + len(distinct)} planes: flange contact ambiguous')
    cyl = [c for c in _revolved(robot_link) if _angle_deg(c['a'], z) <= PARALLEL_DEG]
    if not cyl:
        raise HeadError('robot link has no cylindrical face parallel to the contact normal (flange axis)')
    main = max(cyl, key=lambda c: c['area'])
    a = main['a'] / np.linalg.norm(main['a'])
    origin = main['p'] + (d - z @ main['p']) / (z @ a) * a
    spread = [_line_offset(c['p'], origin, a) for c in cyl if c['r'] >= 0.5 * main['r']]
    pins = [c for c in cyl if abs(c['r'] - pin_radius_mm) <= PIN_RADIUS_TOL_MM
            and _line_offset(c['p'], origin, a) > pin_radius_mm]
    lines: List[np.ndarray] = []
    for c in pins:
        foot = c['p'] - ((c['p'] - origin) @ z) * z
        if not any(np.linalg.norm(foot - f) <= LINE_TOL_MM for f in lines):
            lines.append(foot)
    if len(lines) != 1:
        raise HeadError(f'{len(lines)} dowel-pin hole(s) of radius {pin_radius_mm} mm on the flange (expected 1); '
                        'yaw undefined: fix frames.tool0.pin_radius_mm or set x_file in the map')
    pin = lines[0] - origin
    pin_offset = float(np.linalg.norm(pin))
    pin /= pin_offset
    col, sign = PIN_AXES[pin_axis]
    if col == 1:
        y = sign * pin
        x = np.cross(y, z)
    else:
        x = sign * pin
    rot = frames.frame_from_z_x(z, x)
    residuals: Dict[str, Any] = {
        'contact_plane_gap_mm': float(abs(best[0]['d'] + best[1]['d'])),
        'contact_normal_angle_deg': _angle_deg(best[0]['n'], best[1]['n']),
        'contact_area_robot_mm2': best[0]['area'], 'contact_area_mount_mm2': best[1]['area'],
        'flange_axis_to_normal_deg': _angle_deg(a, z), 'flange_radius_mm': main['r'],
        'flange_axis_spread_mm': float(max(spread)), 'pin_offset_mm': pin_offset,
    }
    mount_cyl = [c for c in _revolved(mount) if _angle_deg(c['a'], z) <= PARALLEL_DEG]
    if mount_cyl:
        m = max(mount_cyl, key=lambda c: c['area'])
        residuals.update(mount_axis_offset_mm=_line_offset(m['p'], origin, a),
                         mount_axis_angle_deg=_angle_deg(m['a'], a), mount_axis_radius_mm=m['r'])
    return frames.make_transform(origin, rot), residuals


def tool0_from_map(t0: Dict[str, Any]) -> np.ndarray:
    origin = _vec3(t0['origin_file_mm'], 'frames.tool0.origin_file_mm')
    z = _unit(t0['z_file'], 'frames.tool0.z_file')
    x = _unit(t0['x_file'], 'frames.tool0.x_file')
    if abs(x @ z) > 1e-6:
        raise HeadError('frames.tool0.x_file must be orthogonal to z_file')
    return frames.make_transform(origin, frames.frame_from_z_x(z, x))


# --- beam -----------------------------------------------------------------------------------------------------

def _vertices(face) -> np.ndarray:
    pts, exp = [], TopExp_Explorer(face, TopAbs_VERTEX)
    while exp.More():
        pts.append(BRep_Tool.Pnt(topods.Vertex(exp.Current())).Coord())
        exp.Next()
    return np.array(pts, dtype=float).reshape(-1, 3)


def estimate_beam(body: TopoDS_Shape, file_T_tool0: np.ndarray) -> Dict[str, Any]:
    """Beam line of the head (file frame): ``{exit_mm, axis, residuals, runner_up}``; see the module docstring."""
    origin = file_T_tool0[:3, 3]
    groups: List[Dict[str, Any]] = []
    for c in _revolved(body, (GeomAbs_Cylinder, GeomAbs_Cone)):
        a = c['a'] / np.linalg.norm(c['a'])
        for g in groups:
            if _angle_deg(a, g['a']) <= PARALLEL_DEG and _line_offset(c['p'], g['p'], g['a']) <= LINE_TOL_MM:
                g['faces'].append(c)
                break
        else:
            groups.append({'a': a, 'p': c['p'], 'faces': [c]})
    if not groups:
        raise HeadError('head body has no cylindrical or conical face: beam axis undefined (set frames.tcp in the map)')
    for g in groups:
        ref = max(g['faces'], key=lambda c: c['area'])
        g['a'], g['p'] = ref['a'] / np.linalg.norm(ref['a']), ref['p']
        pts = np.vstack([_vertices(c['face']) for c in g['faces']] + [np.array([c['c'] for c in g['faces']])])
        dist = np.linalg.norm(pts - origin, axis=1)
        g['reach'], g['far'] = float(dist.max()), pts[int(np.argmax(dist))]
    for g in groups:
        g['area'] = float(sum(c['area'] for c in g['faces']))
    reach_max = max(g['reach'] for g in groups)
    band = [g for g in groups if g['reach'] >= reach_max - REACH_BAND_MM]
    band.sort(key=lambda g: -g['area'])
    beam = band[0]
    groups = [beam] + sorted((g for g in groups if g is not beam), key=lambda g: -g['reach'])
    a = beam['a']
    foot = beam['p'] + ((origin - beam['p']) @ a) * a
    if (beam['far'] - foot) @ a < 0:
        a = -a
    t_faces = max(float(((_vertices(c['face']) - foot) @ a).max()) for c in beam['faces'] if len(_vertices(c['face'])))
    inter = IntCurvesFace_ShapeIntersector()
    inter.Load(body, 1e-6)
    inter.Perform(gp_Lin(gp_Pnt(*foot), gp_Dir(*a)), -1e9, 1e9)
    t_ray = max((inter.WParameter(i) for i in range(1, inter.NbPnt() + 1)), default=None)
    t_tip = t_faces if t_ray is None else max(t_faces, t_ray)
    residuals: Dict[str, Any] = {
        'faces_on_axis': len(beam['faces']),
        'axis_spread_deg': max(_angle_deg(c['a'], a) for c in beam['faces']),
        'axis_offset_spread_mm': max(_line_offset(c['p'], foot, a) for c in beam['faces']),
        'tip_ray_vs_faces_mm': None if t_ray is None else float(abs(t_ray - t_faces)),
        'radii_mm': sorted({round(c['r'], 3) for c in beam['faces']})[:12],
        'reach_mm': beam['reach'], 'area_mm2': beam['area'],
        'candidates_in_reach_band': len(band), 'reach_band_mm': REACH_BAND_MM,
    }
    runner = None
    if len(groups) > 1:
        g = band[1] if len(band) > 1 else groups[1]
        runner = {'reach_mm': g['reach'], 'area_mm2': g['area'], 'faces': len(g['faces']), 'angle_to_beam_deg': _angle_deg(g['a'], a),
                  'offset_from_beam_mm': _line_offset(g['p'], foot, a),
                  'radii_mm': sorted({round(c['r'], 3) for c in g['faces']})[:12]}
    return {'exit_mm': foot + t_tip * a, 'axis': a, 'residuals': residuals, 'runner_up': runner}


def tcp_pose(exit_tool0: np.ndarray, axis_tool0: np.ndarray, nozzle_len_mm: float) -> np.ndarray:
    """``tool0_T_tcp``: beam exit + nozzle along the beam; Z = beam, X = tool0 X (or Y) made orthogonal."""
    hint = np.array([1.0, 0.0, 0.0]) if abs(axis_tool0[0]) < 0.99 else np.array([0.0, 1.0, 0.0])
    return frames.make_transform(exit_tool0 + nozzle_len_mm * axis_tool0, frames.frame_from_z_x(axis_tool0, hint))


