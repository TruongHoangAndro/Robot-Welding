def _bbox(shape) -> np.ndarray:
    box = Bnd_Box()
    box.SetGap(0.0)
    brepbndlib.Add(shape, box)
    return np.array(box.Get(), dtype=float).reshape(2, 3)


def _coverage(face, pos: Optional[np.ndarray], idx: Optional[np.ndarray]) -> float:
    """Triangle area / B-Rep face area (0 for no triangulation). Below 1 by the chordal deficit on curved faces."""
    if pos is None or not len(idx):
        return 0.0
    tri_area = 0.5 * np.linalg.norm(np.cross(pos[idx[:, 1]] - pos[idx[:, 0]], pos[idx[:, 2]] - pos[idx[:, 0]]),
                                    axis=1).sum()
    return float(tri_area / scene._face_area_mm2(face))


def _accept(face, pos, idx, deflection, chord) -> bool:
    """A face mesh is taken when it covers >= RETRY_MIN_AREA_FRACTION of the face area and holds the chord.

    Zero-area sliver triangles are allowed (they add no surface and leave no gap; the area test catches a
    degenerate mesh)."""
    return _coverage(face, pos, idx) >= scene.RETRY_MIN_AREA_FRACTION and deflection <= chord


def _retry_face(face, linear_mm: float, angular_deg: float) -> Tuple[Optional[np.ndarray], Optional[np.ndarray],
                                                                      Dict[str, Any]]:
    """Mesh one face left empty or incomplete by the shape mesher: alone at the same chord with any angle, then
    rebuilt from its natural UV bounds (only if that keeps its area and box), then alone at finer chords. Every
    result must cover >= 99 % of the face area and hold the chord."""
    def grid(factors):
        for factor in factors:
            chord = linear_mm * factor
            for deg in RETRY_ANGLES_DEG:
                breptools.Clean(face)
                BRepMesh_IncrementalMesh(face, chord, False, units.deg_to_rad(deg), False).Perform()
                pos, idx, dfl = scene._face_triangles(face)
                if _accept(face, pos, idx, dfl, chord):
                    return pos, idx, {'method': 'alone', 'linear_deflection_mm': chord, 'angular_deflection_deg': deg,
                                      'achieved_chord_mm': dfl, 'coverage': _coverage(face, pos, idx)}
        return None

    found = grid(RETRY_CHORD_FACTORS[:1])  # same chord, any angle
    if found is not None:
        return found
    umin, umax, vmin, vmax = breptools.UVBounds(face)
    maker = BRepBuilderAPI_MakeFace(BRep_Tool.Surface(face), umin, umax, vmin, vmax, 1e-7)
    if maker.IsDone():  # faces BRepMesh never meshes (real CAD: full-turn cones), rebuilt on their own surface
        rebuilt = maker.Face()
        rebuilt.Orientation(face.Orientation())
        area, area_new = scene._face_area_mm2(face), scene._face_area_mm2(rebuilt)
        box, box_new = _bbox(face), _bbox(rebuilt)
        if abs(area_new - area) <= REBUILD_AREA_REL * area and np.abs(box_new - box).max() <= linear_mm:
            BRepMesh_IncrementalMesh(rebuilt, linear_mm, False, units.deg_to_rad(angular_deg), False).Perform()
            pos, idx, dfl = scene._face_triangles(rebuilt)
            if _accept(rebuilt, pos, idx, dfl, linear_mm):
                return pos, idx, {'method': 'rebuilt_uv_bounds', 'area_mm2': area,
                                  'area_rebuilt_mm2': area_new, 'achieved_chord_mm': dfl,
                                  'coverage': _coverage(rebuilt, pos, idx)}
    found = grid(RETRY_CHORD_FACTORS[1:])  # finer chords
    if found is not None:
        return found
    return None, None, {}


def mesh_faces(shape: TopoDS_Shape, linear_mm: float, angular_deg: float, label: str) -> Dict[str, Any]:
    """Triangles of every face of ``shape`` (solids and free faces alike; file frame, mm, not welded).

    Raises if any face cannot be covered (the collision geometry would have a hole)."""
    breptools.Clean(shape)
    mesher = BRepMesh_IncrementalMesh(shape, linear_mm, False, units.deg_to_rad(angular_deg), True)
    mesher.Perform()
    if not mesher.IsDone():
        raise HeadError(f'{label!r}: tessellation failed')
    verts, tris, retried, missing = [], [], [], []
    offset, area_brep = 0, 0.0
    faces = _faces(shape)
    for k, face in enumerate(faces, start=1):
        area = scene._face_area_mm2(face)
        area_brep += area
        pos, idx, _dfl = scene._face_triangles(face)
        covered = _coverage(face, pos, idx) >= scene.RETRY_MIN_AREA_FRACTION
        if not covered:
            pos, idx, how = _retry_face(face, linear_mm, angular_deg)
            if pos is None:
                missing.append(f'face {k} ({BRepAdaptor_Surface(face).GetType()}, area {area:.3f} mm2, '
                               f'box {np.round(_bbox(face), 2).tolist()})')
                continue
            how['face'] = k
            retried.append(how)
            LOG.warning('%r: face %d meshed again alone (%s)', label, k, how['method'])
        verts.append(pos)
        tris.append(idx + offset)
        offset += len(pos)
    if missing:
        raise HeadError(f'{label!r}: {len(missing)} face(s) without a covering mesh (collision hole): '
                        + '; '.join(missing[:10]))
    return {'verts': np.vstack(verts), 'tris': np.vstack(tris), 'faces_in': len(faces),
            'faces_meshed': len(verts), 'brep_area_mm2': float(area_brep), 'retried': retried}


def _to_tool0(points: np.ndarray, file_T_tool0: np.ndarray) -> np.ndarray:
    return (points - file_T_tool0[:3, 3]) @ file_T_tool0[:3, :3]


def link_meshes(shape: TopoDS_Shape, file_T_tool0: np.ndarray, label: str) -> Dict[str, Any]:
    """Full mesh (welded) and convex hull of one link, both in tool0 (mm)."""
    full = mesh_faces(shape, MESH_LINEAR_DEFLECTION_MM, MESH_ANGULAR_DEFLECTION_DEG, label)
    verts, tris = meshops.weld(_to_tool0(full['verts'], file_T_tool0), full['tris'], MESH_WELD_MM)
    fine = mesh_faces(shape, HULL_LINEAR_DEFLECTION_MM, HULL_ANGULAR_DEFLECTION_DEG, label)
    pts = np.vstack([_to_tool0(fine['verts'], file_T_tool0), verts])
    hv, ht = hull.convex_hull(pts)
    diag = float(np.linalg.norm(pts.max(axis=0) - pts.min(axis=0)))
    if not hull.contains(hv, ht, pts, 1e-6 * diag + 1e-9).all():
        raise HeadError(f'hull of {label!r} does not contain all its tessellation nodes')
    areas = 0.5 * np.linalg.norm(np.cross(verts[tris[:, 1]] - verts[tris[:, 0]],
                                          verts[tris[:, 2]] - verts[tris[:, 0]]), axis=1)
    LOG.info('A18 %s: mesh %d triangles (%d faces), hull %d triangles', label, len(tris), full['faces_in'], len(ht))
    return {'verts': verts, 'tris': tris, 'hull_verts': hv, 'hull_tris': ht, 'faces_in': full['faces_in'],
            'faces_meshed': full['faces_meshed'], 'brep_area_mm2': full['brep_area_mm2'],
            'mesh_area_mm2': float(areas.sum()), 'closed': bool(meshops.is_closed(tris)),
            'retried': full['retried'] + [dict(r, tessellation='hull') for r in fine['retried']]}


